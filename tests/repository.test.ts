import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { IDBFactory, IDBObjectStore } from 'fake-indexeddb'
import { actions, getState, initializeFinance as initializeEmptyFinance, switchWorkspace, accountBalance } from '../src/lib/store'
import { closeDatabase, listBackups, readWorkspace, updateWorkspace } from '../src/lib/repository'
import { createSeed, uid } from '../src/lib/model'
let legacy: Map<string, string>
beforeEach(async () => {
  await closeDatabase()
  vi.stubGlobal('indexedDB', new IDBFactory())
  legacy = new Map()
  vi.stubGlobal('localStorage', { getItem: (key: string) => legacy.get(key) ?? null, setItem: (key: string, value: string) => { legacy.set(key, value) } })
})
afterEach(async () => { vi.restoreAllMocks(); await closeDatabase() })
async function initializeFinance() { await initializeEmptyFinance(); await actions.applyDefaultTemplate() }
describe('durable owner scoped repository', () => {
  it('does not produce trash, backups, or storage writes after ten resets of the initial state', async () => {
    await initializeEmptyFinance()
    await actions.chooseStart('empty')
    const before = await readWorkspace('guest')
    for (let i = 0; i < 10; i++) await actions.reset()
    expect(getState().accounts).toHaveLength(0)
    expect(getState().categories).toHaveLength(0)
    expect(await listBackups('guest')).toHaveLength(0)
    expect(await readWorkspace('guest')).toEqual(before)
  })
  it('clears all active data once, preserves old trash and settings, then becomes a no-op', async () => {
    await initializeFinance()
    const seedIds = getState().accounts.map(row => row.id)
    const categoryIds = getState().categories.map(row => row.id)
    await actions.updateSettings({ theme: 'dark', lang: 'en' })
    await actions.updateAccount(seedIds[0], { initialBalance: 400 })
    await actions.addAccount({ name: 'Extra', type: 'bank', initialBalance: 200 })
    await actions.addTransaction({ accountId: seedIds[0], categoryId: categoryIds[0], type: 'income', amount: 100, date: '2026-11-16' })
    await actions.setBudget(categoryIds[2], 300)
    await actions.addCategory({ name: 'Old trash', type: 'expense' })
    const oldId = getState().categories.find(c => c.name === 'Old trash')!.id
    await actions.deleteCategory(oldId)
    const before = structuredClone(getState())
    expect(await actions.reset()).toBe(true)
    expect(getState().accounts.filter(a => !a.deletedAt)).toHaveLength(0)
    expect(getState().categories.filter(c => !c.deletedAt)).toHaveLength(0)
    expect(getState().accounts.map(a => a.id)).toEqual(before.accounts.map(a => a.id))
    expect(getState().categories.map(c => c.id)).toEqual(before.categories.map(c => c.id))
    expect(getState().transactions.every(t => t.deletedAt)).toBe(true)
    expect(getState().budgets.every(b => b.deletedAt)).toBe(true)
    expect(getState().settings).toEqual(before.settings)
    expect(getState().categories.find(c => c.id === oldId)).toEqual(before.categories.find(c => c.id === oldId))
    expect((await listBackups('guest'))[0].state).toEqual(before)
    const reset = await readWorkspace('guest'); const backups = await listBackups('guest')
    for (let i = 0; i < 10; i++) expect(await actions.reset()).toBe(false)
    expect(await readWorkspace('guest')).toEqual(reset)
    expect(await listBackups('guest')).toEqual(backups)
    await closeDatabase(); await switchWorkspace(null)
    expect(await actions.reset()).toBe(false)
  })
  it('clears presets from the old reset implementation without recreating any identities', async () => {
    await initializeFinance()
    await updateWorkspace('guest', workspace => {
      const old = createSeed(); const active = createSeed(true)
      const at = new Date().toISOString()
      workspace.state = { ...active, accounts: [...old.accounts.map(a => ({ ...a, deletedAt: at })), ...active.accounts], categories: [...old.categories.map(c => ({ ...c, deletedAt: at })), ...active.categories] }
    })
    await switchWorkspace(null); const before = await readWorkspace('guest')
    expect(await actions.reset()).toBe(true)
    expect(getState().accounts).toHaveLength(6)
    expect(getState().categories).toHaveLength(14)
    expect(getState().accounts.every(a => a.deletedAt)).toBe(true)
    expect(getState().categories.every(c => c.deletedAt)).toBe(true)
    expect(getState().accounts.slice(0, 3)).toEqual(before.state.accounts.slice(0, 3))
    expect(await listBackups('guest')).toHaveLength(1)
    expect(await actions.reset()).toBe(false)
  })
  it('does not revive a deleted or permanently removed preset identity', async () => {
    await initializeFinance()
    const accountId = getState().accounts[0].id; const categoryId = getState().categories[0].id
    await actions.deleteAccount(accountId); await actions.purgeOne('account', accountId)
    await actions.deleteCategory(categoryId)
    await actions.reset()
    expect(getState().purged.accounts).toContain(accountId)
    expect(getState().accounts.some(a => a.id === accountId)).toBe(false)
    expect(getState().categories.find(c => c.id === categoryId)?.deletedAt).toBeTruthy()
    expect(getState().accounts.filter(a => !a.deletedAt)).toHaveLength(0)
    expect(getState().categories.filter(c => !c.deletedAt)).toHaveLength(0)
    expect(getState().accounts).toHaveLength(2)
    expect(getState().categories).toHaveLength(7)
    const ids = getState().accounts.map(a => a.id)
    expect(await actions.reset()).toBe(false)
    expect(getState().accounts.map(a => a.id)).toEqual(ids)
  })
  it('preserves historical category types without creating replacement defaults on reset', async () => {
    await initializeFinance(); const categoryId = getState().categories[0].id
    await actions.updateCategory(categoryId, { type: 'expense' })
    await actions.addTransaction({ accountId: getState().accounts[0].id, categoryId, type: 'expense', amount: 10, date: '2026-11-16' })
    await actions.reset()
    expect(getState().categories.find(c => c.id === categoryId)?.type).toBe('expense')
    expect(getState().categories.find(c => c.id === categoryId)?.deletedAt).toBeTruthy()
    expect(getState().categories.filter(c => !c.deletedAt)).toHaveLength(0)
    expect(getState().categories).toHaveLength(7)
    expect(getState().transactions[0].categoryId).toBe(categoryId)
    expect(await actions.reset()).toBe(false)
  })
  it('serializes simultaneous resets so only one backup and one deletion are produced', async () => {
    await initializeFinance()
    await actions.addTransaction({ accountId: getState().accounts[0].id, categoryId: getState().categories[0].id, type: 'income', amount: 10, date: '2026-11-16' })
    expect(await Promise.all([actions.reset(), actions.reset()])).toEqual([true, false])
    expect(await listBackups('guest')).toHaveLength(1)
    expect(getState().accounts).toHaveLength(3)
    expect(getState().categories).toHaveLength(7)
    expect(getState().transactions).toHaveLength(1)
  })
  it('rolls back both reset and its backup if the backup write fails', async () => {
    await initializeFinance(); await actions.updateAccount(getState().accounts[0].id, { initialBalance: 10 })
    const before = await readWorkspace('guest')
    vi.spyOn(IDBObjectStore.prototype, 'put').mockImplementationOnce(() => { throw new DOMException('Full', 'QuotaExceededError') })
    await expect(actions.reset()).rejects.toThrow('Full')
    expect(await readWorkspace('guest')).toEqual(before)
    expect(getState()).toEqual(before.state)
    expect(await listBackups('guest')).toHaveLength(0)
  })
  it('persists CRUD through reload and isolates guest and different users', async () => {
    await initializeFinance()
    await actions.addAccount({ name: 'Guest only', type: 'cash', initialBalance: 700 })
    const guest = getState()
    const userA = uid(); const userB = uid()
    await switchWorkspace(userA)
    expect(getState().accounts.some(a => a.name === 'Guest only')).toBe(false)
    await actions.addAccount({ name: 'A only', type: 'bank', initialBalance: 150 })
    await switchWorkspace(userB)
    expect(getState().accounts.some(a => a.name === 'A only')).toBe(false)
    await switchWorkspace(userA)
    expect(getState().accounts.some(a => a.name === 'A only')).toBe(true)
    await closeDatabase(); await switchWorkspace(null)
    expect(getState()).toEqual(guest)
  })
  it('preserves corrupt raw JSON and refuses to replace it with seeds', async () => {
    legacy.set('finance.v3', '{broken')
    await expect(initializeFinance()).rejects.toThrow('tidak valid')
    expect(legacy.get('finance.v3')).toBe('{broken')
    expect(await (await import('../src/lib/repository')).openDatabase()).toBeDefined()
  })
  it('does not publish a change or partial backup if the write fails', async () => {
    await initializeFinance(); const before = getState()
    vi.spyOn(IDBObjectStore.prototype, 'put').mockImplementationOnce(() => { throw new DOMException('Full', 'QuotaExceededError') })
    await expect(actions.addAccount({ name: 'Cannot save', type: 'cash', initialBalance: 0 })).rejects.toThrow('Full')
    expect(getState()).toEqual(before)
    expect((await readWorkspace('guest')).state).toEqual(before)
  })
  it('serializes concurrent additions across independent transactions', async () => {
    await initializeFinance()
    await Promise.all([actions.addAccount({ name: 'First tab', type: 'cash', initialBalance: 1 }), actions.addAccount({ name: 'Second tab', type: 'bank', initialBalance: 2 })])
    expect(getState().accounts.filter(a => a.name.includes('tab'))).toHaveLength(2)
  })
  it('rejects a stale edit instead of silently overwriting another tab', async () => {
    await initializeFinance(); const id = getState().accounts[0].id
    const results = await Promise.allSettled([actions.updateAccount(id, { name: 'Tab one' }), actions.updateAccount(id, { name: 'Tab two' })])
    expect(results.filter(r => r.status === 'rejected')).toHaveLength(1)
  })
  it('rejects a form based on an older row even after the visible store refreshed', async () => {
    await initializeFinance(); const original = structuredClone(getState().accounts[0])
    await actions.updateAccount(original.id, { initialBalance: 800 })
    await expect(actions.updateAccount(original.id, { name: 'Stale draft', initialBalance: 0 }, original)).rejects.toThrow('tab lain')
    expect(getState().accounts[0].initialBalance).toBe(800)
  })
  it('commits a new category and budget atomically and validates unique budget', async () => {
    await initializeFinance(); const before = getState()
    await expect(actions.addBudgetCategory('Atomic', -5)).rejects.toThrow()
    expect(getState()).toEqual(before)
    await actions.addBudgetCategory('Atomic', 1000)
    const category = getState().categories.find(c => c.name === 'Atomic')!
    expect(getState().budgets.filter(b => b.categoryId === category.id)).toHaveLength(1)
    await actions.setBudget(category.id, 1500)
    expect(getState().budgets.filter(b => b.categoryId === category.id)).toHaveLength(1)
  })
  it('normalizes an edited transfer and protects the destination balance', async () => {
    await initializeFinance(); const [from, to] = getState().accounts
    await actions.addTransaction({ accountId: from.id, targetAccountId: to.id, type: 'transfer', amount: 900, date: '2026-11-15' })
    await actions.updateTransaction(getState().transactions[0].id, { type: 'income', categoryId: getState().categories[0].id })
    expect(accountBalance(to, getState().transactions)).toBe(0)
    expect(accountBalance(from, getState().transactions)).toBe(900)
  })
  it('imports atomically, retains missing cloud identities as tombstones, and backs up the previous version', async () => {
    await initializeFinance(); await actions.addAccount({ name: 'Old', type: 'cash', initialBalance: 300 })
    const before = getState(); const backup = actions.exportJSON()
    await expect(actions.importJSON('{}')).rejects.toThrow()
    expect(getState()).toEqual(before)
    const parsed = JSON.parse(backup); parsed.data.accounts = parsed.data.accounts.filter((a: { name: string }) => a.name !== 'Old')
    await actions.importJSON(JSON.stringify(parsed))
    expect(getState().accounts.find(a => a.name === 'Old')?.deletedAt).toBeTruthy()
    expect((await listBackups('guest'))[0].state).toEqual(before)
    expect(JSON.parse(actions.exportJSON()).data.accounts.some((a: { deletedAt: string }) => a.deletedAt)).toBe(true)
  })
  it('persists purge markers and refuses to remove parents before their children', async () => {
    await initializeFinance(); const id = getState().accounts[0].id
    await actions.addTransaction({ accountId: id, categoryId: getState().categories[0].id, type: 'income', amount: 100, date: '2026-11-15' })
    await actions.deleteAccount(id)
    await expect(actions.purgeOne('account', id)).rejects.toThrow('transaksi')
    const removed = await actions.purgeDeleted()
    expect(removed).toBe(2)
    expect(getState().purged.accounts).toContain(id)
    await closeDatabase(); await switchWorkspace(null)
    expect(getState().purged.accounts).toContain(id)
  })
  it('rolls back all changes when validation fails within a transaction', async () => {
    await initializeFinance(); const before = await readWorkspace('guest')
    await expect(updateWorkspace('guest', workspace => { workspace.state.accounts[0].initialBalance = Infinity })).rejects.toThrow()
    expect(await readWorkspace('guest')).toEqual(before)
  })
  it('does not silently drop an imported identity that was permanently removed', async () => {
    await initializeFinance(); const backup = actions.exportJSON(); const id = getState().accounts[0].id
    await actions.deleteAccount(id); await actions.purgeOne('account', id)
    await expect(actions.importJSON(backup)).rejects.toThrow('dimusnahkan')
    expect(getState().purged.accounts).toContain(id)
  })
})
