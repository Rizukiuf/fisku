test('transfer needs two distinct accounts and saves without any category', async ({ page }) => {
  await openSettings(page)
  const transaction = await openTransaction(page)
  await transaction.getByRole('button', { name: 'Transfer', exact: true }).click()
  await transaction.locator('input[inputmode="numeric"]').fill('100')
  await expect(transaction.getByText('Transfer membutuhkan dua akun yang berbeda.', { exact: true })).toBeVisible()
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  await createEntity(page, 'akun', 'From cash')
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  await createEntity(page, 'akun', 'To bank')
  const from = await transaction.getByLabel('Dari Akun', { exact: true }).inputValue()
  const to = await transaction.getByLabel('Akun Tujuan', { exact: true }).inputValue()
  expect(from).not.toBe(to)
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeEnabled()
  await transaction.getByLabel('Dari Akun', { exact: true }).selectOption(to)
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  await transaction.getByLabel('Akun Tujuan', { exact: true }).selectOption(from)
  await transaction.getByRole('button', { name: 'Simpan', exact: true }).click()
  await expect(transaction).toHaveCount(0)
  const state = await page.evaluate(async () => (await import('/src/lib/store.ts')).getState())
  expect(state.categories).toHaveLength(0)
  expect(state.transactions[0]).toMatchObject({ type: 'transfer', amount: 100, accountId: to, targetAccountId: from })
  expect(state.transactions[0].categoryId).toBeUndefined()
})

test('deleting selected references in another tab requires explicit reselection and retains the draft', async ({ page, context }) => {
  await openSettings(page)
  await page.getByRole('button', { name: 'Gunakan template bawaan', exact: true }).click()
  await expect(page.getByText('BCA', { exact: true })).toBeVisible()
  const other = await context.newPage(); await openSettings(other)
  const transaction = await openTransaction(page)
  await transaction.locator('input[inputmode="numeric"]').fill('750')
  await transaction.locator('input').last().fill('Keep this draft')
  const accountId = await transaction.getByLabel('Akun', { exact: true }).inputValue()
  const categoryId = await transaction.getByLabel('Kategori', { exact: true }).inputValue()
  const remaining = await other.evaluate(async ids => {
    const store = await import('/src/lib/store.ts')
    await store.actions.deleteAccount(ids.accountId)
    await store.actions.deleteCategory(ids.categoryId)
    const state = store.getState()
    return { account: state.accounts.find(row => !row.deletedAt)!.id, category: state.categories.find(row => !row.deletedAt && row.type === 'expense')!.id }
  }, { accountId, categoryId })
  await expect(transaction.getByText('Akun yang dipilih sudah tidak tersedia. Pilih akun kembali.', { exact: true })).toBeVisible()
  await expect(transaction.getByText('Kategori yang dipilih sudah tidak tersedia. Pilih kategori kembali.', { exact: true })).toBeVisible()
  await expect(transaction.getByLabel('Akun', { exact: true })).toHaveValue('')
  await expect(transaction.getByLabel('Kategori', { exact: true })).toHaveValue('')
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  await expect(transaction.locator('input').last()).toHaveValue('Keep this draft')
  await transaction.getByLabel('Akun', { exact: true }).selectOption(remaining.account)
  await transaction.getByLabel('Kategori', { exact: true }).selectOption(remaining.category)
  await transaction.getByRole('button', { name: 'Simpan', exact: true }).click()
  await expect(transaction).toHaveCount(0)
  const saved = await page.evaluate(async () => (await import('/src/lib/store.ts')).getState().transactions[0])
  expect(saved).toMatchObject({ accountId: remaining.account, categoryId: remaining.category, amount: 750, note: 'Keep this draft' })
})

test('a failed account creation keeps the creator open and cancel restores the transaction draft', async ({ page }) => {
  await openSettings(page)
  const transaction = await openTransaction(page)
  await transaction.locator('input[inputmode="numeric"]').fill('123')
  await transaction.locator('input').last().fill('Preserve on failure')
  await transaction.getByRole('button', { name: 'Tambah akun', exact: true }).click()
  const creator = form(page, 'Tambah akun')
  await creator.locator('input').first().fill('Failed account')
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put; let fail = true
    IDBObjectStore.prototype.put = function (...args) {
      if (fail) { fail = false; throw new DOMException('Nested form quota failure', 'QuotaExceededError') }
      return put.apply(this, args)
    }
  })
  await creator.getByRole('button', { name: 'Simpan', exact: true }).click()
  await expect(page.getByText('Nested form quota failure', { exact: true })).toBeVisible()
  await expect(creator).toBeVisible()
  await creator.getByRole('button', { name: 'Batal', exact: true }).click()
  await expect(transaction.locator('input[inputmode="numeric"]')).toHaveValue('123')
  await expect(transaction.locator('input').last()).toHaveValue('Preserve on failure')
  expect(await page.evaluate(async () => (await import('/src/lib/store.ts')).getState().accounts.length)).toBe(0)
})

test('deleted defaults stay deleted after reset and reload until the template is explicitly requested', async ({ page }) => {
  await openSettings(page)
  await page.getByRole('button', { name: 'Gunakan template bawaan', exact: true }).click()
  await expect(page.getByText('BCA', { exact: true })).toBeVisible()
  const original = await page.evaluate(async () => (await import('/src/lib/store.ts')).getState())
  const accountRow = page.locator('li').filter({ has: page.getByText('BCA', { exact: true }) })
  await accountRow.getByRole('button', { name: 'Hapus', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Hapus', exact: true }).click()
  const categoryRow = page.locator('li').filter({ has: page.getByText('Gaji', { exact: true }) })
  await categoryRow.locator('button').last().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Hapus', exact: true }).click()
  await page.locator('summary').filter({ hasText: 'Alat lanjutan' }).click()
  await page.getByRole('button', { name: 'Reset semua data', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Reset semua data', exact: true }).click()
  await expect(page.getByText('Data aktif dikosongkan', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Gunakan template bawaan', exact: true })).toBeVisible()
  const cleared = await page.evaluate(async () => (await import('/src/lib/store.ts')).getState())
  expect(cleared.accounts).toHaveLength(3)
  expect(cleared.categories).toHaveLength(7)
  expect(cleared.accounts.every(row => row.deletedAt)).toBe(true)
  expect(cleared.categories.every(row => row.deletedAt)).toBe(true)
  await page.getByRole('button', { name: 'Gunakan template bawaan', exact: true }).click()
  await expect(page.getByText('BCA', { exact: true }).filter({ visible: true })).toBeVisible()
  const setup = await page.evaluate(async () => (await import('/src/lib/store.ts')).getState())
  expect(setup.accounts.filter(row => !row.deletedAt)).toHaveLength(3)
  expect(setup.categories.filter(row => !row.deletedAt)).toHaveLength(7)
  expect(setup.accounts.filter(row => !row.deletedAt).every(row => !original.accounts.some(old => old.id === row.id))).toBe(true)
  expect(setup.categories.filter(row => !row.deletedAt).every(row => !original.categories.some(old => old.id === row.id))).toBe(true)
})

test('a transaction deleted in another tab cannot be saved again from its open editor', async ({ page, context }) => {
  await openSettings(page)
  await page.getByRole('button', { name: 'Gunakan template bawaan', exact: true }).click()
  await expect(page.getByText('BCA', { exact: true })).toBeVisible()
  const id = await page.evaluate(async () => {
    const store = await import('/src/lib/store.ts'); const state = store.getState()
    await store.actions.addTransaction({ type: 'expense', accountId: state.accounts[0].id, categoryId: state.categories.find(row => row.type === 'expense')!.id, amount: 50, date: '2026-11-16' })
    return store.getState().transactions[0].id
  })
  const other = await context.newPage(); await openSettings(other)
  await page.goto('http://127.0.0.1:5176/#/transactions')
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  const editor = form(page, 'Edit transaksi')
  await other.evaluate(async id => { await (await import('/src/lib/store.ts')).actions.deleteTransaction(id) }, id)
  await expect(editor.getByText('Transaksi ini sudah dihapus atau tidak tersedia. Tutup form dan periksa daftar transaksi.', { exact: true })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  expect(await page.evaluate(async () => (await import('/src/lib/store.ts')).getState().transactions.every(row => row.deletedAt))).toBe(true)
})

test('references added in another tab require selection and clicking the current type preserves that selection', async ({ page, context }) => {
  await openSettings(page)
  const other = await context.newPage(); await openSettings(other)
  const transaction = await openTransaction(page)
  await transaction.locator('input[inputmode="numeric"]').fill('100')
  const ids = await other.evaluate(async () => {
    const store = await import('/src/lib/store.ts')
    const account = await store.actions.addAccount({ name: 'External account', type: 'cash', initialBalance: 0 })
    await store.actions.addCategory({ name: 'First category', type: 'expense' })
    const category = await store.actions.addCategory({ name: 'Second category', type: 'expense' })
    return { account: account.id, category: category.id }
  })
  await expect(transaction.getByLabel('Akun', { exact: true })).toBeEnabled()
  await expect(transaction.getByLabel('Kategori', { exact: true })).toBeEnabled()
  await expect(transaction.getByLabel('Akun', { exact: true })).toHaveValue('')
  await expect(transaction.getByLabel('Kategori', { exact: true })).toHaveValue('')
  await expect(transaction.getByText('Akun yang dipilih sudah tidak tersedia. Pilih akun kembali.', { exact: true })).toHaveCount(0)
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeDisabled()
  await transaction.getByLabel('Akun', { exact: true }).selectOption(ids.account)
  await transaction.getByLabel('Kategori', { exact: true }).selectOption(ids.category)
  await transaction.getByRole('button', { name: 'Pengeluaran', exact: true }).click()
  await expect(transaction.getByLabel('Kategori', { exact: true })).toHaveValue(ids.category)
  await expect(transaction.getByRole('button', { name: 'Simpan', exact: true })).toBeEnabled()
})
